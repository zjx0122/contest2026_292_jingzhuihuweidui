int bsp_lcd_init(void)
{
  struct fb_videoinfo_s vinfo;
  struct fb_planeinfo_s pinfo;
  int ret;

  if (g_fb_fd >= 0)
    {
      return OK;
    }

  g_fb_fd = open(FB_PATH, O_WRONLY);
  if (g_fb_fd < 0)
    {
      lcderr("ERROR: 打开 %s 失败: %d\n", FB_PATH, errno);
      return -errno;
    }

  ret = ioctl(g_fb_fd, FBIOGET_VIDEOINFO, (unsigned long)&vinfo);
  if (ret < 0)
    {
      lcderr("ERROR: 获取视频信息失败: %d\n", ret);
      close(g_fb_fd);
      g_fb_fd = -1;
      return ret;
    }

  ret = ioctl(g_fb_fd, FBIOGET_PLANEINFO, (unsigned long)&pinfo);
  if (ret < 0)
    {
      lcderr("ERROR: 获取平面信息失败: %d\n", ret);
      close(g_fb_fd);
      g_fb_fd = -1;
      return ret;
    }

  g_fb_stride = vinfo.xres * (pinfo.bpp / 8);
  g_fb_size   = g_fb_stride * vinfo.yres;

  lcdinfo("GC9A01 BSP: %dx%d, %dbpp, stride=%d\n",
          vinfo.xres, vinfo.yres, pinfo.bpp, g_fb_stride);

  g_fb_mem = (uint16_t *)malloc(g_fb_size);
  if (g_fb_mem == NULL)
    {
      lcderr("ERROR: 分配 framebuffer 内存失败\n");
      close(g_fb_fd);
      g_fb_fd = -1;
      return -ENOMEM;
    }

  memset(g_fb_mem, 0, g_fb_size);
  return OK;
}

